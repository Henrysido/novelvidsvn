export function translateVoiceNickname(nickname?: string | null, isVi = false): string {
  if (!nickname) return ''
  if (!isVi) return nickname
  return VOICE_NAME_MAP[nickname] || nickname
}

export function translateCountry(country?: string | null, isVi = false): string {
  if (!country) return ''
  if (!isVi) return country
  return COUNTRY_NAME_MAP[country] || country
}

export function translateOccupation(occupation?: string | null, isVi = false): string {
  if (!occupation) return ''
  if (!isVi) return occupation
  return OCCUPATION_MAP[occupation] || occupation
}

export function translateGender(gender?: string | null, isVi = false): string {
  if (!gender) return ''
  if (!isVi) return gender
  if (gender === '男' || gender === '男性') return 'Nam'
  if (gender === '女' || gender === '女性') return 'Nữ'
  if (gender === '未设置') return 'Chưa thiết lập'
  if (gender === '其他') return 'Khác'
  return gender
}
